def material(
    name: str,
    color: Vec3,
    roughness: float = 0.5,
    metallic: float = 0,
    grain: Vec3 | None = None,
) -> bpy.types.Material:
    result = bpy.data.materials.new(name)
    result.diffuse_color = (*color, 1)
    result.use_nodes = True
    tree = result.node_tree
    assert tree is not None
    nodes = tree.nodes
    links = tree.links
    shader = nodes.get("Principled BSDF")
    assert shader is not None
    cast(bpy.types.NodeSocketColor, shader.inputs["Base Color"]).default_value = (
        *color,
        1,
    )
    cast(
        bpy.types.NodeSocketFloat, shader.inputs["Roughness"]
    ).default_value = roughness
    cast(bpy.types.NodeSocketFloat, shader.inputs["Metallic"]).default_value = metallic
    if grain:
        coordinates = nodes.new("ShaderNodeTexCoord")
        stretch = cast(
            bpy.types.ShaderNodeVectorMath, nodes.new("ShaderNodeVectorMath")
        )
        stretch.operation = "MULTIPLY"
        assert stretch.inputs is not None and stretch.outputs is not None
        cast(bpy.types.NodeSocketVector, stretch.inputs[1]).default_value = grain
        noise = nodes.new("ShaderNodeTexNoise")
        assert noise.inputs is not None and noise.outputs is not None
        cast(bpy.types.NodeSocketFloat, noise.inputs["Scale"]).default_value = 8
        cast(bpy.types.NodeSocketFloat, noise.inputs["Detail"]).default_value = 3
        ramp = cast(bpy.types.ShaderNodeValToRGB, nodes.new("ShaderNodeValToRGB"))
        assert ramp.color_ramp is not None
        assert ramp.inputs is not None and ramp.outputs is not None
        ramp.color_ramp.elements[0].color = (*(v * 0.55 for v in color), 1)
        ramp.color_ramp.elements[1].color = (*(min(v * 1.35, 1) for v in color), 1)
        bump = nodes.new("ShaderNodeBump")
        assert bump.inputs is not None and bump.outputs is not None
        assert coordinates.outputs is not None
        cast(bpy.types.NodeSocketFloat, bump.inputs["Strength"]).default_value = 0.24
        cast(bpy.types.NodeSocketFloat, bump.inputs["Distance"]).default_value = 0.008
        links.new(coordinates.outputs["Generated"], stretch.inputs[0])
        links.new(stretch.outputs["Vector"], noise.inputs["Vector"])
        links.new(noise.outputs["Fac"], ramp.inputs["Fac"])
        links.new(ramp.outputs["Color"], shader.inputs["Base Color"])
        links.new(noise.outputs["Fac"], bump.inputs["Height"])
        links.new(bump.outputs["Normal"], shader.inputs["Normal"])
    return result


def finish(
    obj: bpy.types.Object, name: str, mat: bpy.types.Material, bevel: float = 0
) -> bpy.types.Object:
    obj.name = name
    data = obj.data
    assert isinstance(data, (bpy.types.Mesh, bpy.types.Curve))
    data.materials.append(mat)
    if bevel:
        modifier = cast(
            bpy.types.BevelModifier, obj.modifiers.new("Machined edges", "BEVEL")
        )
        modifier.width = bevel
        modifier.segments = 2
        modifier.limit_method = "ANGLE"
        obj.modifiers.new("Face normals", "WEIGHTED_NORMAL")
    return obj


def geometry(
    name: str,
    triangles: list[Triangle],
    mat: bpy.types.Material,
    bevel: float = 0,
    smooth: bool = False,
) -> bpy.types.Object:
    vertices = dict.fromkeys(vertex for triangle in triangles for vertex in triangle)
    indices = {vertex: i for i, vertex in enumerate(vertices)}
    data = bpy.data.meshes.new(name)
    data.from_pydata(
        list(vertices), [], [tuple(indices[v] for v in face) for face in triangles]
    )
    data.update()
    if smooth:
        for i, face in enumerate(data.polygons):
            face.use_smooth = i % 4 < 2
    obj = bpy.data.objects.new(name, data)
    cast(bpy.types.Collection, bpy.context.collection).objects.link(obj)
    return finish(obj, name, mat, bevel)


def box(
    name: str, center: Vec3, size: Vec3, mat: bpy.types.Material, bevel: float = 0.015
) -> bpy.types.Object:
    obj = geometry(name, box_mesh((0, 0, 0), size), mat, bevel)
    obj.location = center
    return obj


def rod(
    name: str,
    start: Vec3,
    end: Vec3,
    radius: float,
    mat: bpy.types.Material,
    sides: int = 16,
) -> bpy.types.Object:
    direction = Vector(end) - Vector(start)
    assert direction.length > 0 and radius > 0
    return geometry(name, cylinder(start, end, radius, sides), mat, smooth=True)


def ring(
    name: str,
    center: Vec3,
    radius: float,
    thickness: float,
    mat: bpy.types.Material,
    vertical: bool = False,
) -> bpy.types.Object:
    vertices: list[Vec3] = []
    for i in range(48):
        a = 2 * pi * i / 48
        for j in range(6):
            b = 2 * pi * j / 6
            r = radius + thickness * cos(b)
            x, y, z = r * cos(a), r * sin(a), thickness * sin(b)
            vertices.append(
                (center[0] + x, center[1] - z, center[2] + y)
                if vertical
                else (center[0] + x, center[1] + y, center[2] + z)
            )
    triangles: list[Triangle] = []
    for i in range(48):
        for j in range(6):
            a, b = i * 6 + j, ((i + 1) % 48) * 6 + j
            c, d = ((i + 1) % 48) * 6 + (j + 1) % 6, i * 6 + (j + 1) % 6
            triangles.extend(
                (
                    (vertices[a], vertices[b], vertices[c]),
                    (vertices[a], vertices[c], vertices[d]),
                )
            )
    obj = geometry(name, triangles, mat)
    for face in cast(bpy.types.Mesh, obj.data).polygons:
        face.use_smooth = True
    return obj


def cable(
    name: str, points: list[Vec3], radius: float, mat: bpy.types.Material
) -> bpy.types.Object:
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.bevel_depth = radius
    curve.bevel_resolution = 2
    curve.use_fill_caps = True
    curve.resolution_u = 12 if len(points) > 2 else 1
    spline = curve.splines.new("BEZIER")
    spline.bezier_points.add(len(points) - 1)
    for point, position in zip(spline.bezier_points, points, strict=True):
        point.co = position
        point.handle_left_type = "AUTO"
        point.handle_right_type = "AUTO"
    obj = bpy.data.objects.new(name, curve)
    cast(bpy.types.Collection, bpy.context.collection).objects.link(obj)
    curve.materials.append(mat)
    return obj


def text(
    name: str, body: str, center: Vec3, size: float, mat: bpy.types.Material
) -> bpy.types.Object:
    curve = cast(bpy.types.TextCurve, bpy.data.curves.new(name, "FONT"))
    curve.body = body
    curve.align_x = "CENTER"
    curve.size = size
    curve.extrude = 0.001
    obj = bpy.data.objects.new(name, curve)
    cast(bpy.types.Collection, bpy.context.collection).objects.link(obj)
    obj.location = center
    obj.rotation_euler = (pi / 2, 0, pi)
    curve.materials.append(mat)
    return obj


def tripod(
    x: float,
    y: float,
    height: float,
    metal: bpy.types.Material,
    rubber: bpy.types.Material,
    floor: float = 0.0355,
) -> None:
    rod("Telescopic stand", (x, y, floor + 0.095), (x, y, height), 0.022, metal)
    for z in (floor + 0.315, floor + (height - floor) * 0.65):
        rod("Stand collar", (x, y, z), (x, y, z + 0.07), 0.034, metal)
        rod("Wing screw", (x, y, z + 0.04), (x + 0.08, y, z + 0.04), 0.011, metal)
    for a in (0, 2 * pi / 3, 4 * pi / 3):
        end = (x + 0.36 * cos(a), y + 0.36 * sin(a), floor)
        rod("Tripod brace", (x, y, floor + 0.265), end, 0.018, metal)
        rod("Rubber foot", end, (end[0], end[1], floor + 0.05), 0.025, rubber)


